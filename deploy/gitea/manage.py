#!/usr/bin/env python3
"""Initialize and maintain the existing Gitea Compose project (Python 3.10+)."""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit

DIRECTORY = Path(__file__).resolve().parent
OVERRIDE = "docker-compose.override.yml"
MARKER = "# Generated by manage.py; edit with configure."
DB_KEYS = ("GITEA__database__USER", "GITEA__database__PASSWD", "GITEA__database__NAME")


def compose(directory: Path, *args: str, capture=False, stdout=None):
    command = ["docker", "compose", "--project-name", "gitea", "--project-directory", str(directory)]
    if (directory / ".env").exists():
        command += ["--env-file", str(directory / ".env")]
    command += ["-f", str(directory / "docker-compose.yml")]
    if (directory / OVERRIDE).exists():
        command += ["-f", str(directory / OVERRIDE)]
    # The saved deployment is authoritative even from a shell with unrelated settings.
    env = {k: v for k, v in os.environ.items() if not k.startswith(("GITEA_", "COMPOSE_")) and k not in ("USER_UID", "USER_GID")}
    return subprocess.run(command + list(args), check=True, env=env, capture_output=capture,
                          stdout=stdout, text=stdout is None)


def read_env(path: Path) -> dict[str, str]:
    """Read manager settings; preserve all original lines when writing dotenv."""
    values = {}
    if path.exists():
        for line in path.read_text().splitlines():
            match = re.match(r"^(?:export\s+)?([A-Za-z_][A-Za-z_0-9]*)\s*=\s*(.*)$", line)
            if match:
                value = match[2].strip()
                if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                    value = value[1:-1]
                values[match[1]] = value
    return values


def atomic_write(path: Path, text: str):
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def write_env(path: Path, settings: dict[str, str]):
    original = path.read_text() if path.exists() else ""
    lines = []
    remaining = dict(settings)
    for line in original.splitlines():
        match = re.match(r"^(?:export\s+)?([A-Za-z_][A-Za-z_0-9]*)\s*=", line)
        if match and match[1] in settings:
            key = match[1]
            if key in remaining:
                lines.append(f"{key}='{remaining.pop(key)}'")
        else:
            lines.append(line)
    lines.extend(f"{key}='{value}'" for key, value in remaining.items())
    atomic_write(path, "\n".join(lines) + "\n")


def detect_lan() -> str:
    # Route lookup asks the kernel; no packet is sent to this destination.
    routes = json.loads(subprocess.check_output(["ip", "-j", "route", "get", "1.1.1.1"], text=True))
    address = routes[0].get("prefsrc", "")
    if not address or routes[0].get("dev") == "lo":
        raise ValueError("Cannot detect a local address; pass --lan-ip explicitly.")
    return address


def ipv4(value: str) -> str:
    address = ipaddress.IPv4Address(value)
    if address.is_unspecified or address.is_multicast or str(address) == "255.255.255.255":
        raise ValueError("Use an assigned unicast IPv4 address; choose --bind all for wildcard publication.")
    return str(address)


def hostname(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?", value):
        raise ValueError("Domain must be an IPv4 address or DNS hostname, without scheme, path, or port.")
    return value


def saved_lan_ips(settings: dict[str, str]) -> list[str]:
    value = settings.get("GITEA_LAN_IPS") or settings.get("GITEA_LAN_IP", "")
    return value.split(",") if value else []


def build_settings(existing: dict[str, str], args) -> dict[str, str]:
    old_domain = existing.get("GITEA_DOMAIN", "")
    old_lans = saved_lan_ips(existing)
    old_lan = existing.get("GITEA_LAN_IP", "")
    if not old_lan:
        try:
            old_lan = str(ipaddress.IPv4Address(old_domain))
        except ipaddress.AddressValueError:
            pass
    mode = args.bind or ("lan" if args.lan_ip is not None else existing.get("GITEA_BIND_MODE", "lan"))
    if mode not in ("lan", "loopback", "all"):
        raise ValueError("Unsupported saved binding mode; run configure with repeated --lan-ip options for every desired address.")
    requested_lans = args.lan_ip or old_lans or ["auto"]
    lans = list(dict.fromkeys(ipv4(detect_lan() if value == "auto" else value) for value in requested_lans))
    lan = lans[0]
    primary = "127.0.0.1" if mode == "loopback" else lan
    domain = args.domain or old_domain
    if not domain or (not args.domain and domain in (*old_lans, old_lan, "127.0.0.1")):
        domain = primary
    domain = hostname(domain)
    root_url = args.root_url or existing.get("GITEA_ROOT_URL", "")
    if not root_url or (not args.root_url and root_url == f"http://{old_domain}:3300/" and domain != old_domain):
        root_url = f"http://{domain}:3300/"
    parsed = urlsplit(root_url)
    if (parsed.scheme not in ("http", "https") or not parsed.hostname or parsed.username is not None
            or parsed.password is not None or parsed.query or parsed.fragment
            or any(c.isspace() or c in "'\"$\\" for c in root_url)):
        raise ValueError("ROOT_URL must be an http(s) URL without credentials, query, fragment, or shell metacharacters.")
    # Accessing .port also rejects malformed/non-numeric ports.
    if parsed.port is not None and not 1 <= parsed.port <= 65535:
        raise ValueError("ROOT_URL port must be between 1 and 65535.")
    root_url = root_url.rstrip("/") + "/"
    ssh_domain = args.ssh_domain or existing.get("GITEA_SSH_DOMAIN", "")
    if not ssh_domain or (not args.ssh_domain and ssh_domain == old_domain):
        ssh_domain = domain
    settings = {"GITEA_LAN_IP": lan, "GITEA_LAN_IPS": ",".join(lans),
                "GITEA_BIND_MODE": mode, "GITEA_DOMAIN": domain,
                "GITEA_ROOT_URL": root_url, "GITEA_SSH_DOMAIN": hostname(ssh_domain)}
    if args.image:
        settings["GITEA_IMAGE"] = image_reference(args.image)
    return settings


def image_reference(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/:@-]*", value):
        raise ValueError("Invalid Gitea image reference.")
    return value


def bind_addresses(settings: dict[str, str]) -> list[str]:
    mode = settings["GITEA_BIND_MODE"]
    if mode == "all":
        return [""]
    if mode == "loopback":
        return ["127.0.0.1"]
    if mode != "lan":
        raise ValueError("Unsupported binding mode; configure an explicit --lan-ip address list.")
    addresses = saved_lan_ips(settings)
    if not addresses or any(not address for address in addresses):
        raise ValueError("No valid addresses for the selected binding mode.")
    return list(dict.fromkeys(addresses))


def override_text(settings: dict[str, str]) -> str:
    ports = [f"{address + ':' if address else ''}{external}:{internal}"
             for address in bind_addresses(settings) for external, internal in ((3300, 3000), (3322, 22))]
    return MARKER + "\nservices:\n  server:\n    ports: !override\n" + "".join(f"      - {json.dumps(port)}\n" for port in ports)


def write_override(directory: Path, settings: dict[str, str]):
    path = directory / OVERRIDE
    if path.exists() and not path.read_text().startswith(MARKER):
        raise ValueError(f"{path.name} is not managed by this script; move it aside or merge it manually.")
    atomic_write(path, override_text(settings))


def existing_data(directory: Path) -> bool:
    config = json.loads(compose(directory, "config", "--format", "json", capture=True).stdout)
    volumes = subprocess.check_output(["docker", "volume", "ls", "--format", "{{.Name}}"], text=True).splitlines()
    return any(volume["name"] in volumes for volume in config.get("volumes", {}).values())


def ensure_credentials(existing: dict[str, str], existing_data: bool) -> dict[str, str]:
    if all(existing.get(key) for key in DB_KEYS):
        return dict(existing)
    if existing_data:
        raise ValueError("Existing Gitea volumes found but database credentials are incomplete in .env; recover the original credentials first.")
    result = dict(existing)
    for key in (DB_KEYS[0], DB_KEYS[2]):
        if not result.get(key):
            result[key] = "gitea"
    if not result.get(DB_KEYS[1]):
        result[DB_KEYS[1]] = secrets.token_urlsafe(36)
    return result


def snapshot_config(directory: Path, destination: Path):
    destination.mkdir(mode=0o700, parents=True, exist_ok=True)
    for name in (".env", "docker-compose.yml", OVERRIDE):
        source = directory / name
        if source.exists():
            shutil.copyfile(source, destination / name)
            (destination / name).chmod(0o600)


def new_backup(directory: Path, kind: str) -> Path:
    parent = directory / "backups"
    parent.mkdir(mode=0o700, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    destination = parent / f"{stamp}-{kind}"
    destination.mkdir(mode=0o700)
    return destination


def private_output(path: Path):
    return os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "wb")


def configure(directory: Path, args):
    if args.command == "init" and existing_data(directory):
        print("Existing Gitea volumes detected; init skipped. Use `python3 manage.py configure` to change configuration.")
        return
    existing = read_env(directory / ".env")
    settings = build_settings(existing, args)
    override = directory / OVERRIDE
    if override.exists() and not override.read_text().startswith(MARKER):
        raise ValueError("Existing Compose override is not managed by this script; refusing to overwrite it.")
    if args.dry_run:
        print(json.dumps(settings, indent=2))
        print(override_text(settings), end="")
        return
    credentials = ensure_credentials(existing, existing_data(directory))
    # Only write newly created credentials; existing quoted/interpolated secrets stay byte-for-byte intact.
    settings.update({key: value for key, value in credentials.items() if key in DB_KEYS and value != existing.get(key)})
    if any((directory / name).exists() for name in (".env", OVERRIDE)):
        snapshot_config(directory, new_backup(directory, "config"))
    old_env = (directory / ".env").read_text() if (directory / ".env").exists() else None
    old_override = override.read_text() if override.exists() else None
    try:
        write_env(directory / ".env", settings)
        write_override(directory, settings)
        compose(directory, "config", "--quiet")
    except Exception:
        for path, old in ((directory / ".env", old_env), (override, old_override)):
            if old is None:
                path.unlink(missing_ok=True)
            else:
                atomic_write(path, old)
        raise
    print(f"Saved configuration: {directory / '.env'} (existing credentials preserved).")
    if args.command == "init" and not args.no_start:
        compose(directory, "up", "-d")
        check(directory, wait=45)
        print("For a new installation, finish administrator setup on the Gitea installation page.")
    elif getattr(args, "apply", False):
        compose(directory, "up", "-d", "--no-deps", "--pull", "never", "server")
        check(directory, wait=45)
    else:
        print("Run `python3 manage.py up` to apply the saved configuration.")


def backup(directory: Path, *, keep_stopped=False) -> Path:
    running = compose(directory, "ps", "--status", "running", "--services", capture=True).stdout.splitlines()
    if "db" not in running:
        raise ValueError("PostgreSQL must be running before backup.")
    destination = new_backup(directory, "data")
    snapshot_config(directory, destination)
    image = subprocess.check_output(["docker", "inspect", "gitea", "--format", "{{.Image}}"], text=True)
    atomic_write(destination / "image-id.txt", image)
    was_running = "server" in running
    success = False
    try:
        if was_running:
            compose(directory, "stop", "server")
        with private_output(destination / "postgres.dump") as output:
            compose(directory, "exec", "-T", "db", "sh", "-c",
                    'exec pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" --format=custom', stdout=output)
        with private_output(destination / "data.tar") as output:
            subprocess.run(["docker", "cp", "gitea:/data/.", "-"], check=True, stdout=output)
        atomic_write(destination / "COMPLETE", "Gitea /data archive and PostgreSQL dump completed.\n")
        success = True
    finally:
        if was_running and (not keep_stopped or not success):
            compose(directory, "start", "server")
    print(f"Backup: {destination}")
    return destination


def effective_settings(directory: Path):
    return json.loads(compose(directory, "config", "--format", "json", capture=True).stdout)["services"]["server"]


def check(directory: Path, *, wait=0):
    settings = effective_settings(directory)
    root_url = settings["environment"]["GITEA__server__ROOT_URL"]
    addresses = list(dict.fromkeys(port.get("host_ip", "") for port in settings["ports"] if port["target"] == 3000))
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    deadline = time.monotonic() + wait
    while True:
        try:
            bindings = json.loads(subprocess.check_output(
                ["docker", "inspect", "gitea", "--format", "{{json .HostConfig.PortBindings}}"], text=True))
            expected = {(str(p["target"]), p.get("host_ip", ""), p["published"]) for p in settings["ports"]}
            actual = {(key.split("/")[0], binding["HostIp"], binding["HostPort"])
                      for key, entries in bindings.items() for binding in (entries or [])}
            if actual != expected:
                raise ValueError("Running port bindings differ from saved configuration; run `python3 manage.py up`.")
            for address in addresses:
                address = "127.0.0.1" if address in ("", "0.0.0.0", "::") else address
                url = f"http://{address}:3300/"
                with opener.open(url, timeout=3) as response:
                    html = response.read().decode()
                    if urlsplit(response.geturl()).path.rstrip("/") == "/install":
                        print(f"OK {url} (installation page ready; finish administrator setup).")
                        continue
                with opener.open(url + "api/v1/version", timeout=3) as response:
                    version = json.load(response)["version"]
                canonical = re.search(r'<meta property="og:url" content="([^"]+)"', html)
                if canonical and canonical[1] != root_url:
                    raise ValueError(f"Running ROOT_URL is {canonical[1]}, expected {root_url}; apply the saved configuration.")
                print(f"OK {url} (Gitea {version}); canonical ROOT_URL: {root_url}")
            return
        except (OSError, ValueError, KeyError) as error:
            if time.monotonic() >= deadline:
                raise ValueError(f"Gitea check failed: {error}") from error
            time.sleep(1)


def parser():
    result = argparse.ArgumentParser(description=__doc__)
    commands = result.add_subparsers(dest="command", required=True)
    for name in ("init", "configure"):
        help_text = "Initialize a new deployment; skip existing Gitea volumes" if name == "init" else "Prepare configuration without upgrading images"
        command = commands.add_parser(name, help=help_text)
        command.add_argument("--lan-ip", action="append", metavar="IP",
                             help="Repeat for multiple local IPv4 addresses; auto selects the route source. Replaces the saved list and selects address binding unless --bind is supplied.")
        command.add_argument("--bind", choices=("lan", "loopback", "all"),
                             help="lan uses the explicit address list; all and loopback override the list")
        command.add_argument("--domain", help="Canonical host without scheme or port")
        command.add_argument("--root-url", help="Canonical external http(s) URL")
        command.add_argument("--ssh-domain", help="Host shown in SSH clone URLs")
        command.add_argument("--image", help="Gitea image tag or digest")
        command.add_argument("--dry-run", action="store_true", help="Preview public configuration without writes or deployment")
        if name == "init":
            command.add_argument("--no-start", action="store_true", help="Only prepare configuration")
        else:
            command.add_argument("--apply", action="store_true", help="Recreate only Gitea using the local image")
    commands.add_parser("up", help="Apply configuration and start services")
    update = commands.add_parser("update", help="Pull Gitea, back up data, and recreate only Gitea")
    update.add_argument("--image", help="New Gitea image tag or digest; PostgreSQL stays unchanged")
    commands.add_parser("backup", help="Back up /data and PostgreSQL with Gitea temporarily stopped")
    commands.add_parser("status", help="Show current containers and desired canonical URL")
    commands.add_parser("check", help="Probe configured HTTP bindings and check ROOT_URL")
    return result


def main(argv=None):
    args = parser().parse_args(argv)
    try:
        if args.command in ("up", "update"):
            # Starting an existing database with fallback credentials can break access.
            ensure_credentials(read_env(DIRECTORY / ".env"), existing_data=True)
        if args.command in ("init", "configure"):
            configure(DIRECTORY, args)
        elif args.command == "status":
            compose(DIRECTORY, "ps")
            settings = effective_settings(DIRECTORY)
            print(f"Configured ROOT_URL: {settings['environment']['GITEA__server__ROOT_URL']}")
        elif args.command == "check":
            check(DIRECTORY)
        elif args.command == "backup":
            backup(DIRECTORY)
        elif args.command == "up":
            compose(DIRECTORY, "config", "--quiet")
            compose(DIRECTORY, "up", "-d", "--pull", "never")
            check(DIRECTORY, wait=45)
        elif args.command == "update":
            if args.image:
                snapshot_config(DIRECTORY, new_backup(DIRECTORY, "config"))
                write_env(DIRECTORY / ".env", {"GITEA_IMAGE": image_reference(args.image)})
            compose(DIRECTORY, "config", "--quiet")
            compose(DIRECTORY, "pull", "server")
            backup(DIRECTORY, keep_stopped=True)
            compose(DIRECTORY, "up", "-d", "--no-deps", "--pull", "never", "server")
            check(DIRECTORY, wait=45)
        return 0
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
