# Executed inside the container with `python3 -c`. Opens the config for
# reading only and prints a JSON summary. Never writes.
_INSPECT_SCRIPT = r"""
import json, sys

path = sys.argv[1]

def mask(value):
    if not value:
        return "<empty>"
    text = str(value)
    return text[:6] + "..." if len(text) > 6 else "<set>"

try:
    with open(path, encoding="utf-8-sig") as fh:
        cfg = json.load(fh)
except FileNotFoundError:
    print(json.dumps({"error": "config not found"}))
    sys.exit(0)
except Exception as exc:
    print(json.dumps({"error": f"{type(exc).__name__}: {exc}"}))
    sys.exit(0)


def keys(value):
    return value if isinstance(value, list) else []


summary = {
    "sources": [
        {
            "id": s.get("id"),
            "type": s.get("type"),
            "api_base": s.get("api_base"),
            "key": mask((s.get("key") or [""])[0]),
        }
        for s in keys(cfg.get("provider_sources"))
    ],
    "models": [
        {
            "id": p.get("id"),
            "model": p.get("model"),
            "source": p.get("provider_source_id"),
            "enable": p.get("enable"),
        }
        for p in keys(cfg.get("provider"))
    ],
    "platforms": [
        {"id": p.get("id"), "type": p.get("type"), "enable": p.get("enable")}
        for p in keys(cfg.get("platform"))
    ],
    "plugins_enabled": cfg.get("plugin_set"),
    "wake_prefix": cfg.get("wake_prefix"),
    "admins": cfg.get("admins_id"),
    "dashboard": {
        "enable": (cfg.get("dashboard") or {}).get("enable"),
        "username": (cfg.get("dashboard") or {}).get("username"),
        "host": (cfg.get("dashboard") or {}).get("host"),
        "port": (cfg.get("dashboard") or {}).get("port"),
        "has_password": bool(
            (cfg.get("dashboard") or {}).get("password")
            or (cfg.get("dashboard") or {}).get("pbkdf2_password")
        ),
    },
}
print(json.dumps(summary, ensure_ascii=False))
"""


def inspect_config(name: str) -> dict:
    """Read AstrBot's config inside the container. Read-only.

    Any failure is returned as a dict with an "error" key so callers can
    degrade gracefully rather than crash the status report.
    """
    try:
        r = subprocess.run(
            [
                "docker",
                "exec",
                name,
                "python3",
                "-c",
                _INSPECT_SCRIPT,
                CONFIG_IN_CONTAINER,
            ],
            capture_output=True,
            text=True,
            timeout=20,
        )
    except Exception as exc:
        return {"error": f"{type(exc).__name__}: {exc}"}

    if r.returncode != 0:
        return {"error": (r.stderr or "inspection failed").strip()[:200]}

    try:
        return json.loads(r.stdout.strip().splitlines()[-1])
    except Exception as exc:
        return {"error": f"unparsable output: {exc}"}


