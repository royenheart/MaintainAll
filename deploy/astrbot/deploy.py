#!/usr/bin/env python3
"""AstrBot — minimal deployment helper.

Deploy only. This script brings the container up, takes it down, and
reports on it. It never writes AstrBot's configuration: no provider
injection, no plugin schema patching, no cmd_config.json edits. All
runtime configuration belongs to the operator and the WebUI.

Commands:
    setup-env   Generate .env (dashboard password, tag, naming)
    up          Pull the image and start the container
    down        Stop and remove the container (volumes kept)
    status      Read-only health check and configuration summary
    logs        Tail container logs
    shell       Open a shell inside the container
"""

from __future__ import annotations

import json
import secrets
import string
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

import click

SCRIPT_DIR = Path(__file__).resolve().parent
COMPOSE_FILE = SCRIPT_DIR / "docker-compose.yml"
ENV_PATH = SCRIPT_DIR / ".env"

CONFIG_IN_CONTAINER = "/AstrBot/data/cmd_config.json"

RED = "red"
GREEN = "green"
YELLOW = "yellow"
CYAN = "cyan"


# ---------------------------------------------------------------------------
# .env
# ---------------------------------------------------------------------------


def read_env() -> dict:
    """Parse .env into a dict. Missing file yields an empty dict."""
    data: dict[str, str] = {}
    if not ENV_PATH.exists():
        return data
    for raw in ENV_PATH.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        data[key.strip()] = value.strip()
    return data


def write_env(data: dict) -> None:
    lines = [
        "# ============================================================",
        "# AstrBot — minimal deployment environment",
        "# Generated by deploy.py setup-env.",
        "# ============================================================",
        "",
        "# --- Required ---",
        f"ASTRBOT_DASHBOARD_PASSWORD={data.get('ASTRBOT_DASHBOARD_PASSWORD', '')}",
        "",
        "# --- Optional: image / update control ---",
        f"ASTRBOT_TAG={data.get('ASTRBOT_TAG', 'latest')}",
        "",
        "# --- Optional: naming ---",
        f"ASTRBOT_CONTAINER={data.get('ASTRBOT_CONTAINER', 'astrbot')}",
        f"ASTRBOT_PORT={data.get('ASTRBOT_PORT', '6185')}",
        f"ASTRBOT_VOLUME={data.get('ASTRBOT_VOLUME', 'astrbot_data')}",
        "",
        "# --- Optional: misc ---",
        f"TZ={data.get('TZ', 'Asia/Shanghai')}",
        "",
    ]
    ENV_PATH.write_text("\n".join(lines) + "\n")


def generate_password(length: int = 20) -> str:
    """Password satisfying AstrBot's complexity rule.

    AstrBot rejects dashboard passwords without an upper case letter, a
    lower case letter and a digit, so generate until all three appear.
    """
    alphabet = string.ascii_letters + string.digits
    while True:
        candidate = "".join(secrets.choice(alphabet) for _ in range(length))
        if (
            any(c.islower() for c in candidate)
            and any(c.isupper() for c in candidate)
            and any(c.isdigit() for c in candidate)
        ):
            return candidate


def password_problem(password: str) -> str | None:
    """Return a human-readable reason the password is invalid, else None."""
    if len(password) < 8:
        return "must be at least 8 characters"
    if not any(c.islower() for c in password):
        return "must contain a lower case letter"
    if not any(c.isupper() for c in password):
        return "must contain an upper case letter"
    if not any(c.isdigit() for c in password):
        return "must contain a digit"
    return None


def ensure_dashboard_password(env: dict) -> str | None:
    """Guarantee a valid dashboard password in .env; return a new one if made.

    AstrBot's ``_resolve_initial_dashboard_password()`` validates the env
    value whenever it has to generate the dashboard credentials, and its
    ``validate_dashboard_password()`` rejects an empty string outright.
    This compose always passes ``ASTRBOT_DASHBOARD_INITIAL_PASSWORD``, so
    a blank (or too weak) value in .env would crash the container on a
    fresh volume with a cryptic ValueError. Substituting a valid value
    before starting removes that failure mode entirely.

    On an already-initialised volume the value is ignored by AstrBot, so
    regenerating is harmless there too.
    """
    password = env.get("ASTRBOT_DASHBOARD_PASSWORD", "")
    problem = password_problem(password) if password else "is not set"
    if not problem:
        return None
    generated = generate_password()
    env["ASTRBOT_DASHBOARD_PASSWORD"] = generated
    write_env(env)
    return generated


# ---------------------------------------------------------------------------
# docker helpers
# ---------------------------------------------------------------------------


def _compose(*args: str, check: bool = False) -> subprocess.CompletedProcess:
    cmd = ["docker", "compose", "-f", str(COMPOSE_FILE), *args]
    return subprocess.run(cmd, cwd=str(SCRIPT_DIR), check=check)


def _compose_capture(*args: str) -> subprocess.CompletedProcess:
    cmd = ["docker", "compose", "-f", str(COMPOSE_FILE), *args]
    return subprocess.run(
        cmd, cwd=str(SCRIPT_DIR), capture_output=True, text=True
    )


def docker_available() -> bool:
    try:
        return subprocess.run(
            ["docker", "version"], capture_output=True, timeout=10
        ).returncode == 0
    except Exception:
        return False


def compose_available() -> bool:
    try:
        return subprocess.run(
            ["docker", "compose", "version"], capture_output=True, timeout=10
        ).returncode == 0
    except Exception:
        return False


def container_name(env: dict) -> str:
    return env.get("ASTRBOT_CONTAINER", "astrbot")


def container_running(name: str) -> bool:
    try:
        r = subprocess.run(
            ["docker", "inspect", "-f", "{{.State.Running}}", name],
            capture_output=True,
            text=True,
            timeout=10,
        )
        return r.stdout.strip() == "true"
    except Exception:
        return False


def http_ok(port: str, path: str = "/", timeout: int = 5) -> bool:
    try:
        with urllib.request.urlopen(
            f"http://127.0.0.1:{port}{path}", timeout=timeout
        ) as resp:
            return resp.status == 200
    except urllib.error.HTTPError as e:
        # A redirect or auth challenge still proves the dashboard is up.
        return e.code in (200, 301, 302, 401, 403)
    except Exception:
        return False


def wait_for_dashboard(port: str, attempts: int = 20, interval: int = 5) -> bool:
    for _ in range(attempts):
        if http_ok(port):
            return True
        time.sleep(interval)
    return False


