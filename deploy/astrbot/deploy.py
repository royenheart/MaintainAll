@click.group(invoke_without_command=True)
@click.pass_context
def cli(ctx):
    """AstrBot — minimal deployment helper. Deploy only, never configures."""
    if ctx.invoked_subcommand is None:
        click.echo(ctx.get_help())


@cli.command("setup-env")
@click.option("--password", default=None, help="Dashboard password (omit to generate)")
@click.option("--tag", default=None, help="Image tag, e.g. v4.26.2 (default: latest)")
@click.option(
    "--volume",
    default=None,
    help="Compose volume name; point at an existing volume to adopt its data",
)
def setup_env(password, tag, volume):
    """Generate .env with a dashboard password and optional overrides."""
    data = read_env()

    if password:
        problem = password_problem(password)
        if problem:
            click.secho(f"Password rejected: {problem}", fg=RED)
            sys.exit(1)
        data["ASTRBOT_DASHBOARD_PASSWORD"] = password
    elif data.get("ASTRBOT_DASHBOARD_PASSWORD"):
        click.echo("  [existing]  ASTRBOT_DASHBOARD_PASSWORD")
    else:
        generated = generate_password()
        data["ASTRBOT_DASHBOARD_PASSWORD"] = generated
        click.secho("  [generated] ASTRBOT_DASHBOARD_PASSWORD", fg=GREEN)
        click.secho(f"              {generated}", fg=CYAN)
        click.secho("  Save it now — it is only shown here.", fg=YELLOW)

    if tag:
        data["ASTRBOT_TAG"] = tag
    if volume:
        data["ASTRBOT_VOLUME"] = volume

    for key, default in (
        ("ASTRBOT_TAG", "latest"),
        ("ASTRBOT_CONTAINER", "astrbot"),
        ("ASTRBOT_PORT", "6185"),
        ("ASTRBOT_VOLUME", "astrbot_data"),
        ("TZ", "Asia/Shanghai"),
    ):
        data.setdefault(key, default)

    write_env(data)
    click.secho(f"\n.env written to {ENV_PATH}", fg=GREEN)
    if data["ASTRBOT_VOLUME"] != "astrbot_data":
        click.secho(
            f"  Volume: {data['ASTRBOT_VOLUME']} (adopting existing data)",
            fg=CYAN,
        )


@cli.command("up")
@click.option("--no-pull", is_flag=True, help="Skip the image pull step")
@click.option("--wait/--no-wait", default=True, help="Wait for the dashboard")
def up(no_pull, wait):
    """Pull the image and start AstrBot."""
    if not docker_available() or not compose_available():
        click.secho("Docker and Docker Compose are required.", fg=RED)
        sys.exit(1)

    if not ENV_PATH.exists():
        click.secho(".env not found — run: ./deploy.py setup-env", fg=YELLOW)
        sys.exit(1)

    env = read_env()
    name = container_name(env)
    port = env.get("ASTRBOT_PORT", "6185")

    generated = ensure_dashboard_password(env)
    if generated:
        click.secho(
            "\nDashboard password was missing or invalid — generated one:", fg=YELLOW
        )
        click.secho(f"  {generated}", fg=CYAN)
        click.secho(
            "  Applied only when AstrBot initialises a fresh volume; ignored\n"
            "  if the volume already holds a dashboard password.",
            fg=YELLOW,
        )

    if not no_pull:
        click.secho("Pulling image...", fg=YELLOW)
        _compose("pull")

    click.secho("Starting...", fg=YELLOW)
    if _compose("up", "-d").returncode != 0:
        click.secho("Startup failed. Check: ./deploy.py logs", fg=RED)
        sys.exit(1)

    if wait:
        if wait_for_dashboard(port):
            click.secho(f"\nDashboard ready: http://127.0.0.1:{port}", fg=GREEN)
        else:
            click.secho(
                f"\nContainer started but the dashboard did not answer on :{port}.",
                fg=YELLOW,
            )
            click.echo("  Inspect with: ./deploy.py logs")

    click.echo(f"\nContainer: {name}")
    click.echo("Next: open the dashboard, then configure providers, plugins and")
    click.echo("IM platforms there. This script does not manage that config.")


@cli.command("down")
@click.option(
    "--wipe",
    is_flag=True,
    help="ALSO DELETE THE DATA VOLUME (destroys credentials, platforms, sessions)",
)
@click.option("--yes", is_flag=True, help="Skip the confirmation prompt for --wipe")
def down(wipe, yes):
    """Stop AstrBot. Volumes are kept unless --wipe is given."""
    if wipe:
        click.secho(
            "WARNING: --wipe removes the data volume. This destroys the "
            "dashboard credentials, IM platform logins, the session "
            "database, workspaces and installed plugin state.",
            fg=RED,
            bold=True,
        )
        if not yes:
            click.confirm("Delete the volume as well?", abort=True)
        _compose("down", "-v")
        click.secho("Container and volume removed.", fg=YELLOW)
    else:
        _compose("down")
        click.secho("Container removed. Volume kept.", fg=GREEN)


@cli.command("status")
@click.option("--json", "as_json", is_flag=True, help="Emit machine-readable JSON")
def status(as_json):
    """Read-only health check and configuration summary."""
    env = read_env()
    name = container_name(env)
    port = env.get("ASTRBOT_PORT", "6185")

    running = container_running(name)
    reachable = http_ok(port) if running else False
    info = inspect_config(name) if running else {"error": "container not running"}

    if as_json:
        click.echo(
            json.dumps(
                {
                    "container": name,
                    "running": running,
                    "dashboard_reachable": reachable,
                    "port": port,
                    "image": env.get("ASTRBOT_TAG", "latest"),
                    "volume": env.get("ASTRBOT_VOLUME", "astrbot_data"),
                    "config": info,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
        return

    def ok(flag):
        return click.style("[OK]", fg=GREEN) if flag else click.style("[--]", fg=YELLOW)

    click.secho(f"AstrBot  ({COMPOSE_FILE.parent})", bold=True)
    click.echo(f"  {ok(running)} container `{name}` running")
    click.echo(f"  {ok(reachable)} dashboard reachable on :{port}")
    click.echo(f"  image tag: {env.get('ASTRBOT_TAG', 'latest')}"
               f"   volume: {env.get('ASTRBOT_VOLUME', 'astrbot_data')}")

    if "error" in info:
        click.echo()
        click.secho(f"  config not inspected: {info['error']}", fg=YELLOW)
        return

    dash = info.get("dashboard", {})
    click.echo()
    click.secho("Dashboard", fg=CYAN)
    click.echo(
        f"  user={dash.get('username')}  host={dash.get('host')}"
        f"  port={dash.get('port')}  password_set={dash.get('has_password')}"
    )

    platforms = info.get("platforms") or []
    click.secho(f"IM platforms ({len(platforms)})", fg=CYAN)
    if not platforms:
        click.echo("  (none configured — AstrBot will not receive any messages)")
    for p in platforms:
        click.echo(f"  {p['id']}  type={p['type']}  enable={p['enable']}")

    sources = info.get("sources") or []
    click.secho(f"Provider sources ({len(sources)})", fg=CYAN)
    for s in sources:
        click.echo(
            f"  {s['id']}  type={s['type']}  api_base={s['api_base']}"
            f"  key={s['key']}"
        )

    models = info.get("models") or []
    click.secho(f"Models ({len(models)})", fg=CYAN)
    for m in models:
        click.echo(
            f"  {m['id']}  model={m['model']}  source={m['source']}"
            f"  enable={m['enable']}"
        )

    click.echo()
    click.echo(f"  wake_prefix={info.get('wake_prefix')}  admins={info.get('admins')}")
    click.echo(f"  plugins={info.get('plugins_enabled')}")


@cli.command("logs")
@click.option("-n", "--lines", default=50, help="Number of lines to show")
@click.option("-f", "--follow", is_flag=True, help="Follow log output")
def logs(lines, follow):
    """Tail container logs."""
    env = read_env()
    args = ["docker", "logs", "--tail", str(lines)]
    if follow:
        args.append("-f")
    args.append(container_name(env))
    subprocess.run(args)


@cli.command("shell")
def shell():
    """Open a shell inside the container."""
    env = read_env()
    subprocess.run(["docker", "exec", "-it", container_name(env), "bash"])


if __name__ == "__main__":
    cli()
